CREATE OR ALTER PROC TransferMoney(
@FORM INT, @TO INT,@AMOUNT INT
)	
AS
BEGIN
	BEGIN TRY	
		BEGIN TRAN
		UPDATE Products SET UnitsInStock += @AMOUNT WHERE ProductID = @TO
		UPDATE Products SET UnitsInStock -= @AMOUNT WHERE ProductID = @FORM
		COMMIT TRAN
	END TRY
	BEGIN CATCH
	ROLLBACK TRAN 
	;THROW 520520,'ERROR囉沒有錢',0
	END CATCH

	SELECT UnitsInStock  FROM Products WHERE ProductID IN (1, 2)
END
GO