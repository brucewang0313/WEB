SELECT * FROM Customers C
WHERE NOT EXISTS (SELECT * FROM Orders WHERE CustomerID=C.CustomerID)
-- EXISTS後的條件 有任何東西就是TRUE，沒有就是FALSE

--找出客戶沒有在員工居住的CITY
SELECT * FROM Customers C
WHERE NOT EXISTS (SELECT * FROM Employees WHERE City=C.City)
--另一種寫法
SELECT * FROM Customers
WHERE City IN(
SELECT DISTINCT CITY FROM Customers
EXCEPT
SELECT DISTINCT CITY FROM Employees
)

--客戶和員工都有的CITY(交集)
SELECT * FROM Customers
WHERE City IN(
SELECT DISTINCT CITY FROM Customers
INTERSECT
SELECT DISTINCT CITY FROM Employees
)

--差集
SELECT DISTINCT CITY FROM Customers
EXCEPT--排除(上差集下)
SELECT DISTINCT CITY FROM Employees

--交集
SELECT DISTINCT CITY FROM Customers
INTERSECT
SELECT DISTINCT CITY FROM Employees
--聯集
SELECT DISTINCT CITY FROM Customers
UNION
SELECT DISTINCT CITY FROM Employees
--也是聯集重疊部分不會扣掉
SELECT DISTINCT CITY FROM Customers
UNION ALL
SELECT DISTINCT CITY FROM Employees

